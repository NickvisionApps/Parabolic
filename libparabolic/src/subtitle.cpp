#include "subtitle.h"
#include <compare>
#include <nlohmann/json.hpp>
#include <nlohmann/json_fwd.hpp>
#include <string>
#include <utility>
#include "translation.h"

namespace parabolic::subtitle
{
    Language::Language(std::string language, bool is_auto_generated)
        : m_language{ std::move(language) },
          m_is_auto_generated{ is_auto_generated }
    {
    }

    const std::string& Language::language() const
    {
        return m_language;
    }

    bool Language::is_auto_generated() const
    {
        return m_is_auto_generated;
    }

    std::string Language::str(const translation::Translator& translator) const
    {
        if (m_is_auto_generated)
        {
            return translator._("{} (Auto-generated)", m_language);
        }
        return m_language;
    }

    std::strong_ordering Language::operator<=>(const Language& rhs) const
    {
        if (m_is_auto_generated != rhs.m_is_auto_generated)
        {
            return static_cast<int>(m_is_auto_generated) <=> static_cast<int>(rhs.m_is_auto_generated);
        }
        return m_language <=> rhs.m_language;
    }

    bool Language::operator==(const Language& rhs) const
    {
        return m_language == rhs.m_language;
    }

    bool Options::include_auto_generated() const
    {
        return m_include_auto_generated;
    }

    void Options::set_include_auto_generated(bool value)
    {
        m_include_auto_generated = value;
    }

    void from_json(const nlohmann::json& json, Language& language)
    {
        if (json.contains("language") && json["language"].is_string())
        {
            language.m_language = json.at("language").get<std::string>();
        }
        else if (json.contains("Language") && json["Language"].is_string())
        {
            language.m_language = json.at("Language").get<std::string>();
        }
        if (json.contains("isAutoGenerated") && json["isAutoGenerated"].is_boolean())
        {
            language.m_is_auto_generated = json.at("isAutoGenerated").get<bool>();
        }
        else if (json.contains("IsAutoGenerated") && json["IsAutoGenerated"].is_boolean())
        {
            language.m_is_auto_generated = json.at("IsAutoGenerated").get<bool>();
        }
    }

    void from_json(const nlohmann::json& json, Options& options)
    {
        if (json.contains("includeAutoGeneratedSubtitles") && json["includeAutoGeneratedSubtitles"].is_boolean())
        {
            options.m_include_auto_generated = json.at("includeAutoGeneratedSubtitles").get<bool>();
        }
        else if (json.contains("IncludeAutoGeneratedSubtitles") && json["IncludeAutoGeneratedSubtitles"].is_boolean())
        {
            options.m_include_auto_generated = json.at("IncludeAutoGeneratedSubtitles").get<bool>();
        }
    }

    void to_json(nlohmann::json& json, const Language& language)
    {
        json = nlohmann::json{
            { "language", language.m_language },
            { "isAutoGenerated", language.m_is_auto_generated },
        };
    }

    void to_json(nlohmann::json& json, const Options& options)
    {
        json = nlohmann::json{
            { "includeAutoGeneratedSubtitles", options.m_include_auto_generated },
        };
    }
}
